#!/usr/bin/env python3
"""Write firestore.rules for 奶娃追蹤 from the campus map data.

The rules only accept spots the app can draw: a point on campus, or a floor
of a building with plans, inside that building. Re-run after the map data
changes; `--check` (run by verify.sh) fails when the rules are out of date.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent / "src" / "data" / "campus-map"
RULES = HERE / "firestore.rules"
# A report may sit a little outside the drawn outline: the step at a door.
MARGIN = 5.0


def box(points):
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return [min(xs), min(ys), max(xs), max(ys)]


def space_points(space):
    if "rect" in space:
        x, y, w, h = space["rect"]
        return [[x, y], [x + w, y + h]]
    return space["polygon"]


def building_box(plan):
    points = []
    for floor in plan["floors"]:
        points += floor["outline"]
        for ring in floor.get("outlines", []):
            points += ring
        for space in floor["spaces"]:
            points += space_points(space)
    return box(points)


def grown(b):
    return [round(b[0] - MARGIN, 1), round(b[1] - MARGIN, 1),
            round(b[2] + MARGIN, 1), round(b[3] + MARGIN, 1)]


def rules():
    campus = json.loads((ASSETS / "campus.json").read_text(encoding="utf-8"))
    names = sorted({b["plan"] for b in campus["buildings"] if b.get("plan")})
    plans = []
    for name in names:
        plan = json.loads((ASSETS / f"{name}.json").read_text(encoding="utf-8"))
        floors = ", ".join(f"'{f['id']}'" for f in plan["floors"])
        b = grown(building_box(plan))
        plans.append(f"        '{plan['id']}': {{'floors': [{floors}], 'box': {b}}}")
    plans = ",\n".join(plans)
    return TEMPLATE.replace("%CAMPUS%", str(grown(box(campus["boundary"])))).replace(
        "%PLANS%", plans
    )


TEMPLATE = """\
rules_version = '2';

// Generated by firebase/naiwa_rules.py from the campus map data; edit
// the template there, not this file.
service cloud.firestore {
  match /databases/{database}/documents {
    function signedIn() {
      return request.auth != null;
    }

    // Campus metres, east (x) and south (y) of the centre: [left, top,
    // right, bottom], with a few metres to spare.
    function campusBox() {
      return %CAMPUS%;
    }

    // Buildings with floor plans, in their own metres.
    function plans() {
      return {
%PLANS%
      };
    }

    function inside(d, b) {
      return d.x is number && d.y is number
        && d.x >= b[0] && d.x <= b[2] && d.y >= b[1] && d.y <= b[3];
    }

    // The plans are built once per check: rules stop after 1000
    // expressions, and the table alone is a few hundred.
    function validFloor(d) {
      let plan = plans().get(d.building, null);
      return plan != null
        && d.floor in plan.floors
        && inside(d, plan.box)
        && (!('room' in d) || (d.room is string && d.room.size() <= 40));
    }

    function validSpot(d) {
      return d.kind == 'campus'
        ? !('building' in d) && !('floor' in d) && !('room' in d)
          && inside(d, campusBox())
        : d.kind == 'floor' && d.building is string && validFloor(d);
    }

    // Reports carry no account or device id, so nobody can follow one
    // reporter around campus. Firestore's TTL policy on expiresAt deletes
    // them. Anyone may read them: niu-life.app/map shows them without
    // signing in; the map writes through anonymous sign-in.
    match /naiwaReports/{id} {
      allow get: if true;
      allow list: if request.query.limit <= 100;
      allow create: if signedIn()
        && request.resource.data.keys().hasOnly(
          ['v', 'kind', 'x', 'y', 'building', 'floor', 'room', 'mood', 'at', 'expiresAt'])
        && request.resource.data.v == 1
        && request.resource.data.mood in ['here', 'sleeping', 'walking', 'eating', 'gone']
        && request.resource.data.at == request.time
        && request.resource.data.expiresAt is timestamp
        && request.resource.data.expiresAt > request.time
        && request.resource.data.expiresAt <= request.time + duration.value(3, 'h')
        && validSpot(request.resource.data)
        // Written in the same batch as the reporter's turn below.
        && getAfter(/databases/$(database)/documents/naiwaReporters/$(request.auth.uid)).data.last == request.time;
      allow update, delete: if false;
    }

    // One report every five minutes per anonymous sign-in; only its owner
    // can read when that was.
    match /naiwaReporters/{uid} {
      allow get: if signedIn() && request.auth.uid == uid;
      allow create: if signedIn() && request.auth.uid == uid
        && request.resource.data.keys().hasOnly(['last'])
        && request.resource.data.last == request.time;
      allow update: if signedIn() && request.auth.uid == uid
        && request.resource.data.keys().hasOnly(['last'])
        && request.resource.data.last == request.time
        && request.time > resource.data.last + duration.value(5, 'm');
      allow delete: if false;
    }

    match /{document=**} {
      allow read, write: if false;
    }
  }
}
"""


def main():
    text = rules()
    if "--check" in sys.argv:
        if not RULES.exists() or RULES.read_text(encoding="utf-8") != text:
            print("firebase/firestore.rules is out of date; run python3 firebase/naiwa_rules.py", file=sys.stderr)
            return 1
        print("naiwa rules: up to date")
        return 0
    RULES.write_text(text, encoding="utf-8")
    print("wrote firebase/firestore.rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
